async function deferBootstrap(source, target, prefix, required) {
const index = await readFile(source, "utf8");
const bootstrap = /<script id="sap-ui-bootstrap"[\s\S]*?<\/script>/.exec(index);
if (bootstrap === null) {
  if (required) throw new Error(`${source}: sap-ui-bootstrap script not found`);
  return;
}
// the bootstrap tag's attributes, set on a script element the loader creates
// once the worker controls the page (the tag itself must not appear inside a
// script: "</script>" would end it)
const attributes = {};
for (const m of bootstrap[0].replace(/^<script /, "").matchAll(/([\w-]+)="([^"]*)"|([\w-]+)='([^']*)'/g)) {
  attributes[m[1] ?? m[3]] = m[2] ?? m[4];
}
const loader = `<script>
    // preview deployment: the OData service is answered by a service worker,
    // so it has to control this page before UI5 asks for $metadata. When it
    // cannot, say so instead of booting into a blank list report.
    (async () => {
      const explain = (title, detail) => {
        document.body.innerHTML = "";
        const main = document.createElement("main");
        main.style.cssText = "max-width:40rem;margin:3rem auto;padding:0 1rem;font:16px/1.5 system-ui,sans-serif";
        const h = document.createElement("h1");
        h.style.fontSize = "1.3rem";
        h.textContent = title;
        const p = document.createElement("pre");
        p.style.whiteSpace = "pre-wrap";
        p.textContent = detail;
        const a = document.createElement("p");
        a.innerHTML = 'The gateway runs in a service worker. <a href="${prefix}">Install it again</a>, try another browser, or check that service workers and site data are allowed for this site.';
        main.append(h, p, a);
        document.body.append(main);
      };
      if (!("serviceWorker" in navigator)) {
        explain("This browser cannot run the preview", "navigator.serviceWorker is not available (private window, or service workers turned off).");
        return;
      }
      const expected = new URL(${JSON.stringify(`${prefix}sw.js`)}, location.href).href;
      if (navigator.serviceWorker.controller?.scriptURL !== expected) {
        try {
          await navigator.serviceWorker.register(${JSON.stringify(`${prefix}sw.js`)}, {scope: ${JSON.stringify(prefix)}});
          // A controller from a broader scope is not our backend. Wait for
          // this deployment's own worker, not just any non-null controller.
          for (let waited = 0; navigator.serviceWorker.controller?.scriptURL !== expected && waited < 60000; waited += 100) {
            await new Promise((tick) => setTimeout(tick, 100));
          }
          if (navigator.serviceWorker.controller?.scriptURL !== expected) {
            // a navigation after the registration is controlled for sure; once
            const key = "stg-preview-reload";
            if (!sessionStorage.getItem(key)) {
              sessionStorage.setItem(key, "1");
              location.reload();
              return;
            }
            sessionStorage.removeItem(key);
            throw new Error("the expected service worker does not control this page: " + expected);
          }
        } catch (error) {
          explain("The preview could not start", String(error && error.stack || error));
          return;
        }
      }
      // one round trip before UI5: the worker must be the one answering
      try {
        const probe = await fetch(${JSON.stringify(`${prefix}sap/opu/odata/sap/ZSTG_DEMO_SRV/`)}, {headers: {accept: "application/json"}});
        if (!probe.ok) {
          explain("The gateway did not answer", "GET ${prefix}sap/opu/odata/sap/ZSTG_DEMO_SRV/ returned " + probe.status + "\\n\\n" + (await probe.text()).slice(0, 2000));
          return;
        }
      } catch (error) {
        explain("The gateway did not answer", String(error));
        return;
      }
      const boot = document.createElement("script");
      const attributes = ${JSON.stringify(attributes)};
      for (const name of Object.keys(attributes)) {
        boot.setAttribute(name, attributes[name]);
      }
      document.head.appendChild(boot);
    })();
  </script>`;
await writeFile(target, index.replace(bootstrap[0], loader), "utf8");
}
